// Define a function named 'add' that accepts three parameters: a, b, and c
function add(a, b, c) {
    // Return the sum of the three parameters
    return a + b + c;
}

// Call the 'add' function with the arguments
let num = add(20, 3, 40);

// Print the result stored in num
console.log(num);

// Define an array named 'num2' containing three numeric elements
let num2 = [10, 20, 30];

// Use the spread operator (...) to print 
console.log(...num2);