//Numeric/Number literals can be represented in different formats
//1.int
//2.float
//3.binary
//4.hexadecimal
//5.octal
//6. etc...


let age=18; // This is a number/numeric/int literal
console.log(typeof age, " - Age type");
let height=5.9; // This is a number/float literal
console.log(typeof height, " - Height type");
let pi=3.14; // This is a number/float literal
console.log(typeof pi, " - Pi type");
let negativeNumber=-10; // This is a number/numeric/int literal
console.log(typeof negativeNumber, " - Negative Number type");          
let binaryNumber=0b1010; // This is a binary number literal
console.log(typeof binaryNumber, " - Binary Number type");
let hexNumber=0xFF; // This is a hexadecimal number literal
console.log(typeof hexNumber, " - Hexadecimal Number type");
let octalNumber=0o12; // This is an octal number literal
console.log(typeof octalNumber, " - Octal Number type");
let decimalNumber=12; // This is a decimal number literal
console.log(typeof decimalNumber, " - Decimal Number type");
let bigIntNumber=1234567890123456789012345678901234567890n; // This is a BigInt number literal
console.log(typeof bigIntNumber, " - BigInt Number type");
let smallIntNumber=1234567890123456789012345678901234567890n; // This is a BigInt number literal
console.log(typeof smallIntNumber, " - SmallInt Number type");