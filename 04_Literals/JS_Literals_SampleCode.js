let age=18; // This is a number/numeric literal
let height=5.9; // This is a number literal
let pi=3.14; // This is a number literal
let negativeNumber=-10; // This is a number literal
let binaryNumber=0b1010; // This is a binary number literal
let hexNumber=0xFF; // This is a hexadecimal number literal
let octalNumber=0o12; // This is an octal number literal

//Numeric/Number literals can be represented in different formats
//1.numric/number
//2.float
//3.binary
//4.hexadecimal
//5.octal
//6. etc...


let studentName="Bharath"; // This is a string literal
let isStudent=true; // This is a boolean literal    
let nullValue=null; // This is a null literal
let undefinedValue; // This is an undefined literal
let person={name:"Bharath", age:18}; // This is an object literal


//typeof operator is used to find the type of a literal / data type of a literal
console.log(typeof age, " - Age type");
console.log(typeof height, " - Height type");
console.log(typeof pi, " - is Pi Type");
console.log(typeof studentName, " - Student Name type");
console.log(typeof isStudent, " - Student type");
console.log(typeof nullValue, " - Null value type");
console.log(typeof undefinedValue, " - Undefined value type");
console.log(typeof person, " - Person type");