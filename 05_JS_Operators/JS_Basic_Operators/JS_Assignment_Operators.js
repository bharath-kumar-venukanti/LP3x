// JavaScript Assignment Operators.

// Simple assignment (=)
let a = 10;
console.log("a =", a); // 10

// Add and assign (+=)
let b = 5;
b += 3;
console.log("b += 3 ->", b); // 8

// Subtract and assign (-=)
let c = 10;
c -= 4;
console.log("c -= 4 ->", c); // 6

// Multiply and assign (*=)
let d = 6;
d *= 3;
console.log("d *= 3 ->", d); // 18

// Divide and assign (/=)
let e = 20;
e /= 4;
console.log("e /= 4 ->", e); // 5

// Modulus and assign (%=)
let f = 10;
f %= 3;
console.log("f %= 3 ->", f); // 1

// Exponent and assign (**=)
let g = 2;
g **= 3;
console.log("g **= 3 ->", g); // 8
