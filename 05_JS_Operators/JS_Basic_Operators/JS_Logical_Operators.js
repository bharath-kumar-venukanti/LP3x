let a = true;
let b = false;

// Logical AND
console.log("--------------Logical AND--------------");
// console.log(a && b);
let andResult = a && b;
console.log("AND Result: " + andResult);

// Logical OR
console.log("--------------Logical OR--------------");
let orResult = a || b;
console.log("OR Result: " + orResult);

// Logical NOT
console.log("--------------Logical NOT--------------");
let notResult = !a;
console.log("NOT Result: " + notResult);    

